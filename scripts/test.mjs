// ── fake React ─────────────────────────────────────────────────────────────
// Each component invocation gets its own hook table, keyed by the component's
// source text plus its occurrence at that position in the tree. Re-rendering
// reuses the same tables, so state survives an interaction like React's.
const instances = new Map();
let state = { table: {}, index: 0, key: "" };
/** One stable identity per component function. */
const identityOf = new WeakMap();
/**
 * One hook slot per call position. The slot is namespaced by hook kind so a
 * `useState` and a `useRef` never share a cell: a component that calls them in
 * any order keeps its own values across renders.
 */
const useSlot = (kind) => {
  const key = `${kind}:${String(state.index++)}`;
  if (!(key in state.table)) state.table[key] = undefined;
  return key;
};
/**
 * Resolve a hook table at call time (not at render time): a setter captured by
 * an old render must still write into the instance's current table, exactly
 * like React's dispatch, which is bound to the fiber rather than the render.
 */
const tableOf = (instanceKey) => {
  if (!instances.has(instanceKey)) instances.set(instanceKey, {});
  return instances.get(instanceKey);
};
/** Every state write bumps this; a render that wrote state is re-run once, like React. */
const renderEpoch = { value: 0 };
const reactStub = {
  Fragment: Symbol("Fragment"),
  useState: (initial) => {
    const instanceKey = state.key;
    const slot = useSlot("state");
    const table = state.table;
    if (table[slot] === undefined) table[slot] = typeof initial === "function" ? initial() : initial;
    const read = () => tableOf(instanceKey)[slot];
    const write = (value) => {
      // Bound to the instance, not this render: React's dispatch survives a
      // stale closure passed to an event handler.
      const live = tableOf(instanceKey);
      live[slot] = typeof value === "function" ? value(live[slot]) : value;
      renderEpoch.value += 1;
    };
    return [read(), write];
  },
  useEffect: () => {},
  useMemo: (factory) => factory(),
  useRef: (value) => {
    const key = useSlot("ref");
    if (state.table[key] === undefined) state.table[key] = { current: value };
    return state.table[key];
  },
  useCallback: (fn) => fn,
  useSyncExternalStore: (subscribe, getSnapshot) => {
    subscribe();
    return getSnapshot();
  },
  createElement: (type, props, ...children) => ({ type, props: { ...(props ?? {}), children } })
};
