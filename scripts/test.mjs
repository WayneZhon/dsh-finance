/** Aggregate one month the way `fixture` (lib/analysis.js) does. */
const snapshotOf = (ledger, month, now) => {
  const inMonth = ledger.txns.filter((txn) => monthOf(txn.date) === month);
  const sum = (list) => list.reduce((total, txn) => total + txn.amount, 0);
  const income = sum(inMonth.filter((txn) => txn.direction === "income"));
  const expense = sum(inMonth.filter((txn) => txn.direction === "expense"));
  const byCategoryMap = new Map();
  for (const txn of inMonth.filter((t) => t.direction === "expense")) {
    const entry = byCategoryMap.get(txn.category) ?? { amount: 0, count: 0 };
    entry.amount += txn.amount;
    entry.count += 1;
    byCategoryMap.set(txn.category, entry);
  }
  const byCategory = [...byCategoryMap.entries()]
    .map(([category, entry]) => ({ category, amount: entry.amount, share: expense > 0 ? entry.amount / expense : 0, count: entry.count }))
    .sort((a, b) => b.amount - a.amount);
  const trend = [-5, -4, -3, -2, -1, 0].map((delta) => {
    const key = shift(month, delta);
    const list = ledger.txns.filter((txn) => monthOf(txn.date) === key);
    const inc = sum(list.filter((txn) => txn.direction === "income"));
    const exp = sum(list.filter((txn) => txn.direction === "expense"));
    return { month: key, income: inc, expense: exp, balance: inc - exp };
  });
  const topExpenses = inMonth
    .filter((txn) => txn.direction === "expense")
    .slice()
    .sort((a, b) => b.amount - a.amount)
    .slice(0, 5)
    .map((txn) => ({ id: txn.id, date: txn.date, merchant: txn.merchant, amount: txn.amount, category: txn.category }));
  const assetTotal = ledger.assets.reduce((total, asset) => total + asset.value, 0);
  const kindMap = new Map();
  for (const asset of ledger.assets) kindMap.set(asset.kind, (kindMap.get(asset.kind) ?? 0) + asset.value);
  const byKind = [...kindMap.entries()].map(([kind, amount]) => ({ kind, amount, share: assetTotal > 0 ? amount / assetTotal : 0 })).sort((a, b) => b.amount - a.amount);
  const liabTotal = ledger.liabilities.reduce((total, item) => total + item.balance, 0);
  const day = (stamp) => new RealDate(stamp).getDate();
  const liabilities = ledger.liabilities.map((item) => {
    const today = day(now);
    const dueInDays = item.dueDay >= today ? item.dueDay - today : 30 + item.dueDay - today;
    return { ...item, dueInDays, overdue: false };
  });
  const netWorth = assetTotal - liabTotal;
  let anchor = netWorth;
  const netWorthTrend = new Array(trend.length);
  for (let index = trend.length - 1; index >= 0; index -= 1) {
    netWorthTrend[index] = { month: trend[index].month, netWorth: anchor };
    anchor -= trend[index].balance;
  }
  const holdings = ledger.holdings.map((item) => {
    // `costPrice` and `price` are fen per unit, so 1000 units at ¥40.00 cost
    // ¥40,000 — `cost` is fen, matching the Host's `buildInvest`.
    const cost = Math.round(item.shares * item.costPrice);
    const value = Math.round(item.shares * item.price);
    return { ...item, cost, value, pnl: value - cost, pnlRate: cost > 0 ? (value - cost) / cost : 0 };
  });
  const cost = holdings.reduce((total, item) => total + item.cost, 0);
  const value = holdings.reduce((total, item) => total + item.value, 0);
  const typeMap = new Map();
  for (const item of holdings) typeMap.set(item.type, (typeMap.get(item.type) ?? 0) + item.value);
  const byType = [...typeMap.entries()].map(([type, amount]) => ({ type, value: amount, share: value > 0 ? amount / value : 0 }));
  const budgets = ledger.budgets.map((budget) => {
    const spent = inMonth.filter((txn) => txn.direction === "expense" && txn.category === budget.category).reduce((total, txn) => total + txn.amount, 0);
    return { id: budget.id, category: budget.category, limit: budget.limit, spent, used: budget.limit > 0 ? spent / budget.limit : 0, over: spent > budget.limit };
  });
  const budgetTotal = { limit: budgets.reduce((total, b) => total + b.limit, 0), spent: budgets.reduce((total, b) => total + b.spent, 0) };
  budgetTotal.used = budgetTotal.limit > 0 ? budgetTotal.spent / budgetTotal.limit : 0;
  const goals = ledger.goals.map((goal) => {
    const remaining = Math.max(0, goal.target - goal.saved);
    return { ...goal, progress: goal.target > 0 ? Math.min(1, goal.saved / goal.target) : 0, remainingMonths: 7, monthlyNeeded: Math.ceil(remaining / 7) };
  });
  const monthsAvailable = [...new Set(ledger.txns.map((txn) => monthOf(txn.date)))].sort().reverse();
  const tips = [];
  if (expense > 0) tips.push({ level: "info", title: `应急金约可覆盖 5 个月开销`, detail: "手上能随时取用的钱约 ¥12,000。" });
  const over = budgets.find((row) => row.over);
  if (over !== undefined) tips.push({ level: "warn", title: `${over.category}超支了`, detail: `预算 ¥${String(Math.round(over.limit / 100))}，已花 ¥${String(Math.round(over.spent / 100))}。` });
  if (income > expense) tips.push({ level: "good", title: "这个月有结余", detail: "继续保持。" });
  return {
    month,
    summary: { income, expense, balance: income - expense, txnCount: inMonth.length, autoClassified: inMonth.length, autoRate: 1 },
    byCategory,
    byPurpose: [],
    trend,
    topExpenses,
    assets: { total: assetTotal, byKind, items: ledger.assets },
    liabilities: { total: liabTotal, items: liabilities, upcoming: liabilities.filter((item) => item.monthlyPayment > 0 && item.dueInDays <= 30) },
    netWorth,
    netWorthTrend,
    invest: { cost, value, pnl: value - cost, pnlRate: cost > 0 ? (value - cost) / cost : 0, byType, items: holdings },
    budgets,
    budgetTotal,
    goals,
    tips,
    monthsAvailable,
    // The real Host passes its settings through (the panel reads `demo` from it),
    // so the stand-in must as well.
    settings: { currency: "CNY", emergencyMonths: 6, ...(ledger.settings ?? {}) }
  };
};

