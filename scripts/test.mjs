test("a real Alipay export (366 rows, preamble and all) previews and imports", async () => {
  // The fixture Lead generated: Alipay's own layout, four preamble lines before
  // the header, GBK-friendly content. The panel sends the bytes as base64 and
  // the Host does the parsing, so the preview here is the Host's answer.
  const csv = read("scripts/fixtures/demo-alipay.csv");
  const { ui, tree: opened } = await open();
  press(opened, "导入账单");
  let tree = await settlePage(ui);
  const fileInput = findAll(tree, (node) => node.type === "input" && node.props.type === "file")[0];
  assert.ok(fileInput !== undefined, "a file input exists");
  fileInput.props.onChange({
    target: { files: [{ name: "demo-alipay.csv", base64: Buffer.from(csv, "utf8").toString("base64") }] }
  });
  tree = await flush(ui);
  assert.equal(host.lastImport.encoding, "base64", "bytes go up as base64");
  assert.ok(host.lastImport.decoded >= 300, `the Host parsed the whole file (${String(host.lastImport.decoded)} rows)`);
  const stat = textOfClass(tree, "dshfw-wizard__stat")[0] ?? "";
  assert.match(stat, /^共 \d+ 笔，自动归类 \d+ 笔（\d+%）$/u, `the preview states the total and the auto rate (have ${stat})`);
  const selects = findAll(tree, (node) => node.type === "select" && String(node.props.className ?? "").includes("dshfw-select--sm"));
  assert.ok(selects.length > 0 && selects.length <= 30, `a category dropdown per preview row, capped at 30 (have ${String(selects.length)})`);
  // Change one category, then import.
  selects[0].props.onChange({ target: { value: "教育" } });
  tree = await settlePage(ui);
  press(tree, "确认入库");
  tree = await flush(ui);
  assert.equal(host.lastConfirm.rows[0].category, "教育", "the corrected category travels");
  assert.ok(host.lastConfirm.rows.length > 0, "rows travel to the confirm route");
  assert.match(textOf(tree), /导入完成/, "the result step");
});

