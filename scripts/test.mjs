/** Classify a pasted row the way the rule engine would, well enough to test. */
const classify = (merchant, direction) => {
  if (direction === "income") return { category: INCOME_CATEGORY, confidence: "rule" };
  const table = [
    [/星巴克|瑞幸|咖啡|海底捞|餐/u, "餐饮"],
    [/滴滴|地铁|公交|打车/u, "交通"],
    [/淘宝|京东|拼多多/u, "购物"],
    [/电影|游戏|KTV/u, "娱乐"],
    [/话费|移动|联通|电信/u, "通讯"]
  ];
  for (const [pattern, category] of table) if (pattern.test(merchant)) return { category, confidence: "rule" };
  return { category: "其他", confidence: "default" };
};
/**
 * Parse a pasted CSV into preview rows (header-driven, comma separated).
 * Real exports carry preamble lines (Alipay puts four before the header), so
 * the header is the first line that actually contains a date and an amount
 * column — the same shape the Host's parser detects.
 */
const parseCsv = (text) => {
  const lines = String(text).split(/\r?\n/u).filter((line) => line.trim() !== "");
  if (lines.length === 0) return [];
  let headerAt = lines.findIndex((line) => /交易时间|日期|时间/u.test(line) && /金额/u.test(line));
  if (headerAt < 0) headerAt = 0;
  const header = lines[headerAt].split(",").map((cell) => cell.trim());
  const at = (names) => header.findIndex((cell) => names.includes(cell));
  const dateAt = at(["日期", "交易时间", "时间"]);
  const merchantAt = at(["商户", "交易对方", "摘要"]);
  const amountAt = at(["金额", "金额(元)"]);
  const directionAt = at(["收/支", "类型"]);
  const rows = [];
  for (const line of lines.slice(headerAt + 1)) {
    const cells = line.split(",").map((cell) => cell.trim());
    const amountText = String(cells[amountAt] ?? "").replace(/[¥￥,\s]/gu, "");
    const value = Math.round(Number(amountText) * 100);
    if (!Number.isFinite(value) || value === 0) continue;
    const directionCell = directionAt >= 0 ? cells[directionAt] ?? "" : "";
    const direction = /不计收支/u.test(directionCell) ? "skip" : /收入|收/u.test(directionCell) ? "income" : "expense";
    if (direction === "skip") continue;
    const merchant = cells[merchantAt] ?? "";
    const found = classify(merchant, direction);
    rows.push({ date: cells[dateAt] ?? "", amount: Math.abs(value), direction, merchant, account: "支付宝", note: "", category: found.category, purpose: "生活必须", confidence: found.confidence, raw: {} });
  }
  return rows;
};

