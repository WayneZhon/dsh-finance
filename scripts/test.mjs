/** Pure presentational components are expanded like plain functions. */
const PRESENTATIONAL = new Set(["IconChevronLeft", "IconChevronRight", "IconUpload", "IconMore", "IconPlus", "IconClose", "IconTrash", "IconCheck", "IconSearch", "IconInfo", "IconWarn", "IconGood", "IconSpark", "IconWallet", "PanelIcon"]);
/** Materialize a tree the way React would, one hook table per component. */
const render = (node, path = "root", seen = new Map()) => {
  let current = node;
  let steps = 0;
  while (current !== null && current !== undefined && typeof current === "object" && !Array.isArray(current) && typeof current.type === "function") {
    if (steps > 40) throw new Error(`component chain too deep at ${path}`);
    steps += 1;
    const type = current.type;
    // Identity = the component's own source text. A stable id per function is
    // enough here and immune to the hash collisions a text digest can hit.
    if (!identityOf.has(type)) identityOf.set(type, `${String(type.name)}#${String(identityOf.size)}`);
    const source = PRESENTATIONAL.has(type.name) ? type.name : identityOf.get(type);
    let hash = 2166136261;
    for (let index = 0; index < source.length; index += 1) hash = Math.imul(hash ^ source.charCodeAt(index), 16777619);
    const identity = `${String(type.name)}@${(hash >>> 0).toString(36)}`;
    const occurrence = seen.get(identity) ?? 0;
    seen.set(identity, occurrence + 1);
    // React identifies an instance by its position, not by render order alone.
    // A call site is the pair (component, path), and both are stable across
    // commits because the tree shape is.
    const key = `${identity}@${path}`;
    const table = tableOf(key);
    const previous = state;
    state = { table, index: 0, key };
    try {
      current = type(current.props);
    } finally {
      state = previous;
    }
  }
  // A bare array of children (a component returning a list) is not an element.
  if (current === null || current === undefined || current === false || current === true) return current;
  if (Array.isArray(current)) return current.map((child, index) => renderChildren(child, `${path}.${String(index)}`, seen));
  if (typeof current !== "object" || current.props === undefined) return current;
  return { ...current, props: { ...current.props, children: renderChildren(current.props.children, `${path}.c`, seen) } };
};
/**
 * Materialize a children value of any depth. `jsx()` from a real runtime
 * accepts a static array literal as `children` and does NOT flatten it, so
 * nested component elements can appear several array levels deep; every one of
 * them is expanded, while plain strings/numbers are left alone.
 */
const renderChildren = (value, path, seen, depth = 0) => {
  if (depth > 24) throw new Error(`children nested too deep at ${path}`);
  if (Array.isArray(value)) return value.map((child, index) => renderChildren(child, `${path}.${String(index)}`, seen, depth + 1));
  if (value !== null && typeof value === "object" && "props" in value) return render(value, path, seen);
  return value;
};
/** Every readable string in a tree, in order. */
const flatten = (node, texts = []) => {
  if (node === null || node === undefined || typeof node === "boolean") return texts;
  if (Array.isArray(node)) {
    for (const child of node) flatten(child, texts);
    return texts;
  }
  if (typeof node === "object" && "props" in node) {
    flatten(node.props.children, texts);
    return texts;
  }
  texts.push(String(node));
  return texts;
};
